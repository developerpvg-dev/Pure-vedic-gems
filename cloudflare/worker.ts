type KvGetPut = {
  get(key: string): Promise<string | null>;
  put(key: string, value: string): Promise<void>;
};

type Env = Record<string, unknown> & {
  CRON_SECRET?: string;
  NEXT_PUBLIC_SITE_URL?: string;
  CF_VERSION_METADATA?: { id: string };
  WORKER_SELF_REFERENCE?: { fetch(request: Request): Promise<Response> };
  NEXT_TAG_CACHE_KV?: KvGetPut;
};
type Ctx = { waitUntil(promise: Promise<unknown>): void };
type Geo = { city?: string; country?: string; regionCode?: string; latitude?: string; longitude?: string };

const handler = openNext as { fetch(req: Request, env: Env, ctx: Ctx): Promise<Response> };

function defaultCache(): Cache {
  return (caches as unknown as { default: Cache }).default;
}

/** WordPress / PHP probes — never a real route here; reject before OpenNext boots. */
export function isJunkBotPath(pathname: string): boolean {
  const p = pathname.toLowerCase();
  return p.endsWith('.php') || p.includes('/wp-admin') || p.includes('/wp-login') || p.includes('/xmlrpc.php');
}

/** Warm only when the Worker Cache API miss would otherwise cold-render for the next visitor. */
export async function warmPathIfCold(
  origin: string,
  path: string,
  self: { fetch(request: Request): Promise<Response> },
  version = '',
  gen = ''
): Promise<'hit' | 'warmed'> {
  const request = new Request(origin + path);
  const key = await edgeCacheKey(request, version, gen);
  if (key && (await defaultCache().match(key))) return 'hit';
  await self.fetch(request).then((r) => r.arrayBuffer());
  return 'warmed';
}

export function withClientHeaders(request: Request): Request {
  const headers = new Headers(request.headers);
  // Self-binding requests (warm cron, DO revalidation) have no Host; OpenNext queues ISR revalidation for headers.host.
  if (!headers.has('host')) headers.set('host', new URL(request.url).host);
  for (const key of [...headers.keys()]) {
    if (key.startsWith('x-vercel-ip-') || key === 'x-forwarded-for' || key === 'x-real-ip') {
      headers.delete(key);
    }
  }
  const ip = request.headers.get('cf-connecting-ip');
  if (ip) {
    headers.set('x-forwarded-for', ip);
    headers.set('x-real-ip', ip);
  }
  const cf = (request as Request & { cf?: Geo }).cf;
  const geo: [string, string | undefined][] = [
    ['x-vercel-ip-country', cf?.country ?? request.headers.get('cf-ipcountry') ?? undefined],
    ['x-vercel-ip-country-region', cf?.regionCode],
    // Vercel URI-encodes the city; readers decodeURIComponent it.
    ['x-vercel-ip-city', cf?.city ? encodeURIComponent(cf.city) : undefined],
    ['x-vercel-ip-latitude', cf?.latitude],
    ['x-vercel-ip-longitude', cf?.longitude],
  ];
  for (const [key, value] of geo) if (value && value !== 'XX') headers.set(key, value);
  return new Request(request, { headers });
}

/** Header-only geo lookup polled by every storefront page; skips booting Next (~275ms CPU per call). */
export function currencySuggestResponse(request: Request): Response {
  return Response.json(currencySuggestion(withClientHeaders(request).headers), {
    headers: { 'Cache-Control': 'private, no-store' },
  });
}

const worker = {
  async fetch(request: Request, env: Env, ctx: Ctx) {
    const url = new URL(request.url);
    if (isJunkBotPath(url.pathname)) {
      return new Response(null, { status: 404 });
    }
    if (request.method === 'GET' && url.pathname === '/api/currency/suggest') {
      return currencySuggestResponse(request);
    }
    const gen = await readEdgeCacheGen(env.NEXT_TAG_CACHE_KV);
    const key = await edgeCacheKey(request, env.CF_VERSION_METADATA?.id, gen);
    if (!key) return handler.fetch(withClientHeaders(request), env, ctx);
    const cache = defaultCache();
    const hit = await cache.match(key);
    if (hit) return withBrowserRevalidate(hit);
    const response = await handler.fetch(withClientHeaders(request), env, ctx);
    const copy = edgeCacheCopy(response);
    if (copy) ctx.waitUntil(cache.put(key, copy));
    return response;
  },

  async scheduled(controller: { cron: string }, env: Env, ctx: Ctx) {
    const origin = (env.NEXT_PUBLIC_SITE_URL || 'https://www.purevedicgems.com').replace(/\/$/, '');
    if (controller.cron === WARM_CRON) {
      // Through the service binding, not fetch(origin): a route Worker fetching its own zone would hit Vercel.
      const self = env.WORKER_SELF_REFERENCE;
      const version = env.CF_VERSION_METADATA?.id ?? '';
      const gen = await readEdgeCacheGen(env.NEXT_TAG_CACHE_KV);
      // Skipped while Ratna is off, so the cron doesn't boot Next every interval for nothing.
      const ratnaIdle =
        env.AGENT_ENABLED === 'true'
          ? handler.fetch(
              new Request(`${origin}/api/cron/ratna-idle-sessions`, {
                headers: { authorization: `Bearer ${env.CRON_SECRET ?? ''}` },
              }),
              env,
              ctx
            )
          : null;
      await Promise.allSettled([
        ratnaIdle,
        ...(self ? WARM_PATHS.map((p) => warmPathIfCold(origin, p, self, version, gen)) : []),
      ]);
      return;
    }
    const req = new Request(`${origin}/api/cron/purge-product-trash`, {
      headers: { authorization: `Bearer ${env.CRON_SECRET ?? ''}` },
    });
    const res = await handler.fetch(req, env, ctx);
    if (!res.ok) {
      throw new Error(`purge-product-trash failed: ${res.status} ${await res.text().catch(() => '')}`);
    }
  },
};

export default worker;
