/**
 * Worker entry (wrangler `main`) wrapping the OpenNext handler.
 *
 * 1. Client IP / geo: the app reads `x-forwarded-for` (rate limits) and `x-vercel-ip-*` (geo),
 *    which Vercel used to set. Here they are overwritten from Cloudflare's own data on every
 *    request, so clients can't spoof them.
 * 2. Cron: product-trash purge + cache warm (triggers in wrangler.jsonc), called in-process.
 * 3. Edge cache for `public, s-maxage` responses and ISR pages (see edge-cache.ts).
 * 4. Cache warm-up of the busiest pages when cold, so real visitors rarely find caches empty.
 */
import { edgeCacheCopy, edgeCacheKey, withBrowserRevalidate } from './edge-cache';
import { readEdgeCacheGen } from './edge-cache-gen';
import { currencySuggestion } from '../src/lib/currency/geo';

const WARM_CRON = '*/15 * * * *';
// ponytail: fixed list of top pages. Subcategory pages left out — warming them costs more than it saves.
