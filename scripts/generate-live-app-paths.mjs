/**
 * Regenerates src/lib/live-app-paths.generated.ts from the Next.js page tree.
 * Used by legacy-redirects so WP dump entries can never steal live routes.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const appDir = path.join(root, 'src', 'app');
const outFile = path.join(root, 'src', 'lib', 'live-app-paths.generated.ts');

function walkPages(dir, acc = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) {
      if (ent.name === 'api' || ent.name.startsWith('_')) continue;
      walkPages(p, acc);
    } else if (/^page\.(t|j)sx?$/.test(ent.name)) {
      acc.push(p);
    }
  }
  return acc;
}

function fileToRoute(file) {
  let rel = path.relative(appDir, path.dirname(file)).split(path.sep).join('/');
  if (!rel || rel === '.') return '/';
  const parts = rel
    .split('/')
    .filter((seg) => !(seg.startsWith('(') && seg.endsWith(')')) && !seg.startsWith('@'));
  return `/${parts.join('/')}`.replace(/\/+/g, '/');
}

const routes = [...new Set(walkPages(appDir).map(fileToRoute))]
  .filter((r) => !r.includes('['))
  .sort();

const body = `/* AUTO-GENERATED by scripts/generate-live-app-paths.mjs — do not edit. */
export const LIVE_APP_EXACT_PATHS = new Set<string>([
${routes.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
]);
`;

fs.writeFileSync(outFile, body);
console.log(`wrote ${routes.length} live paths → ${path.relative(root, outFile)}`);
